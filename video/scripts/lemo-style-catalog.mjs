export function normalizeLemoStyleId(value) {
  const key = String(value || "").trim().toLowerCase()
    .normalize("NFD").replace(/[\\u0300-\\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  if (!key) return null;
  if (LEMO_STYLE_CATALOG.some((style) => style.id === key)) return key;
  return VETOR_ALIASES[key] || null;
}

export function resolveLemoStyle(value) {
  const id = normalizeLemoStyleId(value) || "glass-product";
  const style = LEMO_STYLE_CATALOG.find((item) => item.id === id) || LEMO_STYLE_CATALOG.find((item) => item.id === "glass-product");
  return { ...style, attribution: "Lemo-Opuscar style index; Vetor-authored render treatment" };
}

export function listLemoStyles() {
  return LEMO_STYLE_CATALOG.map(({ id, name, category, family, imageGenerationRequired }) => ({
    id, name, category, family, imageGenerationRequired,
  }));
}
